export function getMetricLabel(metric: MetricDefinition, locale: 'bn' | 'en' | 'ar' = 'bn'): string {
  if (locale === 'ar' && metric.labelAr) return metric.labelAr;
  if (locale === 'en' && metric.labelEn) return metric.labelEn;
  return metric.labelBn;
}

export function getGroupTitle(group: MetricGroup, locale: 'bn' | 'en' | 'ar' = 'bn'): string {
  if (locale === 'ar' && group.titleAr) return group.titleAr;
  if (locale === 'en' && group.titleEn) return group.titleEn;
  return group.titleBn;
}

export function getMetricUnit(metric: MetricDefinition, locale: 'bn' | 'en' | 'ar' = 'bn'): string | undefined {
  if (locale === 'ar' && metric.unitAr) return metric.unitAr;
  if (locale === 'en' && metric.unitEn) return metric.unitEn;
  return metric.unitBn;
}
