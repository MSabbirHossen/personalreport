export type MetricType = 'count' | 'duration_minutes' | 'boolean' | 'text';

export type AggregationType =
  | 'sum'
  | 'count_active_days'
  | 'avg_answered_days'
  | 'avg_calendar_days'
  | 'last_value'
  | 'none';

export interface MetricDefinition {
  id: string;
  groupId: string;
  labelBn: string;
  labelEn: string;
  labelAr?: string;
  type: MetricType;
  unitBn?: string;
  unitEn?: string;
  unitAr?: string;
  min?: number;
  max?: number;
  aggregation: AggregationType;
  descriptionBn?: string;
  descriptionEn?: string;
  descriptionAr?: string;
  isRequired?: boolean;
}

